function multiplicarNumeros(n1, n2, n3) {
    const resultado = n1* n2* n3;
    return resultado;
}
const resultadoFinal = multiplicarNumeros(6, 8, 9);
console.log(`O resultado da multiplicação dos três numeros é: ${resultadoFinal}`);
const resultadoFinal2 = multiplicarNumeros(4, 2, 10);
console.log(`O resultado da multiplicação dos três numeros é: ${resultadoFinal2}`);